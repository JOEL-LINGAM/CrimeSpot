"""Builds the shared context (dataset + global filters) once per run and hands it to a page."""
import os
from dataclasses import dataclass, field
from pathlib import Path

import streamlit as st

from src.config import load_config, resolve
from src.metrics_utils import partial_months
from . import data as D
from . import components as UI


@dataclass
class Ctx:
    tag: str
    ds_dir: Path
    meta: dict
    months: list
    categories: list
    filters: D.Filters
    hour_block: int
    cell_deg: float
    partial: list
    is_synthetic: bool
    has_area: bool
    has_clusters: bool
    loader: object = field(default=None)

    @property
    def info(self): return self.meta.get("info", {})


def _no_data_screen(root):
    UI.hero("CrimeScope", "Historical crime pattern analysis · PySpark + Streamlit")
    st.error(f"No processed dataset found in `{root}`.", icon="📂")
    st.markdown("Run the Spark pipeline first (the dashboard only reads its Parquet output):\n"
                "```powershell\npython scripts\\make_sample_data.py --rows 20000\n"
                "python scripts\\run_pipeline.py --config config\\config.sample.yaml --input data\\sample\\synthetic_sample.csv --tag sample\n```\n"
                "or, with the real dataset in `data\\raw\\crimes.csv`:\n```powershell\npython scripts\\run_pipeline.py\n```")
    st.stop()


def build_context() -> Ctx:
    cfg = load_config()
    root = resolve(cfg["paths"]["processed_dir"])
    tags = D.list_datasets(root)
    if not tags:
        _no_data_screen(root)
    default = os.environ.get("CRIMESCOPE_TAG")
    idx = tags.index(default) if default in tags else 0
    with st.sidebar:
        st.markdown("### 🛰️ CrimeScope")
        st.caption("Historical crime analytics · PySpark")
        tag = st.selectbox("Dataset", tags, index=idx, help="Folders under data/processed/ produced by the pipeline.") \
            if len(tags) > 1 else tags[0]
    ds_dir = root / tag
    meta = D.load_meta(ds_dir)
    loader_tmp = type("T", (), {"d": str(ds_dir), "m": UI._mt(ds_dir)})
    ym = UI.c_table(loader_tmp.d, loader_tmp.m, "agg_year_month")
    cats = UI.c_table(loader_tmp.d, loader_tmp.m, "agg_category")
    months = sorted(ym.year_month.unique().tolist())
    categories = cats.sort_values("incidents", ascending=False).category.tolist()
    info = meta["info"]
    an = cfg.get("analytics", {})
    k = lambda n: f"{tag}:{n}"

    def reset():
        st.session_state[k("months")] = (months[0], months[-1])
        st.session_state[k("cats")] = []
        st.session_state[k("hours")] = (0, 23)
        st.session_state[k("day")] = "All"

    with st.sidebar:
        st.markdown("#### Global filters")
        st.caption("Applied to every page that supports them.")
        rng = st.select_slider("Date range (month)", options=months, value=(months[0], months[-1]), key=k("months"))
        sel_cats = st.multiselect("Crime categories", categories, key=k("cats"), placeholder="All categories")
        hrs = st.slider("Hour of day", 0, 23, (0, 23), key=k("hours"))
        day = st.radio("Day type", D.DAY_TYPES, horizontal=True, key=k("day"))
        st.button("↺ Reset filters", on_click=reset, width="stretch")
        f = D.Filters(rng[0], rng[1], tuple(sel_cats), hrs[0], hrs[1], day)
        active = [x for x, on in [("dates", rng != (months[0], months[-1])), (f"{len(sel_cats)} categories", bool(sel_cats)),
                                  ("hours", hrs != (0, 23)), (day.lower(), day != "All")] if on]
        st.caption("Active: " + (", ".join(active) if active else "none (full dataset)"))
        st.divider()
        st.caption(f"Dataset: {info.get('name', tag)}")
    ctx = Ctx(tag=tag, ds_dir=ds_dir, meta=meta, months=months, categories=categories, filters=f,
              hour_block=an.get("map_hour_block", 3), cell_deg=info.get("grid_cell_degrees", cfg["features"]["grid_cell_degrees"]),
              partial=partial_months(info.get("date_min", ""), info.get("date_max", "")),
              is_synthetic=bool(info.get("is_synthetic")), has_area=(ds_dir / "cube_area").exists(),
              has_clusters=(ds_dir / "cell_clusters").exists())
    ctx.loader = UI.Loader(ctx)
    return ctx


PAGE_TITLES = {"overview": "Executive Overview", "map": "Interactive Crime Map", "temporal": "Temporal Patterns",
               "category": "Category Explorer", "hotspots": "Hotspot Intelligence", "compare": "Comparative Analytics",
               "perf": "Big Data Performance Lab", "quality": "Data Quality & Methodology"}


def run_page(key: str, with_nav=False):
    """Used by app.py (inside st.navigation) and by tests (one page at a time)."""
    import importlib
    UI.inject_css()
    ctx = build_context()
    if ctx.is_synthetic:
        UI.banner("⚠️ <b>SYNTHETIC DEVELOPMENT DATA</b> - generated by scripts/make_sample_data.py. "
                  "Nothing on this page is real crime data.")
    errs = D.validate_filters(ctx.filters)
    if errs:
        st.error(" ".join(errs)); st.stop()
    mod = importlib.import_module(f"dashboard.page_{key}")
    mod.render(ctx)
